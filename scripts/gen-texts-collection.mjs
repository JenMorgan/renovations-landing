#!/usr/bin/env node
/**
 * Regenerates the "Website texts" collection in admin/config.yml from the
 * structure of the default language file.
 *
 *   node scripts/gen-texts-collection.mjs
 *
 * Run this after adding or renaming a key in content/locales/*.json — the
 * editor has to list every key, because keys it does not know about would be
 * dropped from the file when an editor saves it.
 */
import { readFile, writeFile } from 'node:fs/promises';

const CONFIG = 'admin/config.yml';
const START = '  # >>> generated by scripts/gen-texts-collection.mjs — do not edit by hand';
const END = '  # <<< end generated';

const site = JSON.parse(await readFile('content/site.json', 'utf8'));
const locales = site.site.locales;
const base = JSON.parse(await readFile(`content/locales/${site.site.defaultLocale}.json`, 'utf8'));

const GROUP_LABELS = {
  meta: 'Search engine title and description',
  nav: 'Menu labels',
  cta: 'Buttons and links',
  hero: 'Top block (hero)',
  sections: 'Section headings',
  project: 'Case study labels',
  filters: 'Project filter buttons',
  prices: 'Price wording',
  forms: 'Form labels and messages',
  footer: 'Footer',
  a11y: 'Labels for screen readers',
  options: 'Drop-down options',
};
const TECHNICAL = ['name', 'nativeName', 'htmlLang', 'dir'];

const humanize = (key) =>
  GROUP_LABELS[key] ||
  key.replace(/([a-z0-9])([A-Z])/g, '$1 $2').replace(/^./, (c) => c.toUpperCase()).replace(/(\d+)$/, ' $1');

const yamlString = (v) => `"${String(v).replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;

function fieldFor(key, value, depth) {
  const pad = '  '.repeat(depth);
  const label = humanize(key);

  if (Array.isArray(value)) {
    return [
      `${pad}- name: ${key}`,
      `${pad}  label: ${yamlString(label)}`,
      `${pad}  widget: list`,
      `${pad}  required: false`,
      `${pad}  field: { name: item, label: "Option", widget: string }`,
    ];
  }
  if (value && typeof value === 'object') {
    const inner = Object.entries(value).flatMap(([k, v]) => fieldFor(k, v, depth + 2));
    return [
      `${pad}- name: ${key}`,
      `${pad}  label: ${yamlString(label)}`,
      `${pad}  widget: object`,
      `${pad}  collapsed: true`,
      `${pad}  fields:`,
      ...inner,
    ];
  }
  const long = typeof value === 'string' && value.length > 90;
  const hint = TECHNICAL.includes(key) ? ', hint: "Technical value — leave as it is"' : '';
  return [
    `${pad}- { name: ${key}, label: ${yamlString(label)}, widget: ${long ? 'text' : 'string'}, required: false${hint} }`,
  ];
}

const fields = Object.entries(base).flatMap(([k, v]) => fieldFor(k, v, 5));

const block = [
  START,
  '  - name: texts',
  '    label: "Website texts"',
  '    files:',
  ...locales.flatMap((code) => [
    `      - name: texts_${code}`,
    `        label: "Website texts — ${code.toUpperCase()}"`,
    `        file: content/locales/${code}.json`,
    '        description: "Headings, buttons and form labels. Leave a field empty to fall back to the default language."',
    '        fields:',
    ...fields,
  ]),
  END,
];

const config = await readFile(CONFIG, 'utf8');
const before = config.indexOf(START);
const after = config.indexOf(END);
const next = before === -1
  ? `${config.trimEnd()}\n\n${block.join('\n')}\n`
  : `${config.slice(0, before)}${block.join('\n')}${config.slice(after + END.length)}`;
await writeFile(CONFIG, next);
console.log(`Wrote the "Website texts" collection for [${locales.join(', ')}]: ${fields.length} field lines per language`);
